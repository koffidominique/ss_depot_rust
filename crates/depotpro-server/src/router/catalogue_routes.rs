// ============================================================================
// Routes Axum : Référentiels catalogue, tarification & catalogue V3
// ============================================================================

use axum::routing::{get, put};
use axum::Router;

use crate::handlers::{
    catalogue_disposables, catalogue_price_items_and_history, catalogue_refs, catalogue_units,
    catalogue_v3, catalogue_v4, catalogue_variants_and_prices, packaging_components,
};
use crate::state::AppState;

pub(crate) fn catalogue_router() -> Router<AppState> {
    Router::new()
        // Référentiels de base du catalogue
        .route(
            "/api/brands",
            get(catalogue_refs::list_brands).post(catalogue_refs::create_brand),
        )
        .route(
            "/api/brands/:id",
            put(catalogue_refs::update_brand).delete(catalogue_refs::delete_brand),
        )
        .route(
            "/api/bottle-profiles",
            get(packaging_components::list_bottle_profiles_pc)
                .post(packaging_components::create_bottle_profile_pc),
        )
        .route(
            "/api/bottle-profiles/:id",
            put(catalogue_refs::update_bottle_profile)
                .delete(catalogue_refs::delete_bottle_profile),
        )
        .route(
            "/api/crate-types",
            get(packaging_components::list_crate_types_pc)
                .post(packaging_components::create_crate_type_pc),
        )
        .route(
            "/api/crate-types/:id",
            put(catalogue_refs::update_crate_type).delete(catalogue_refs::delete_crate_type),
        )
        .route(
            "/api/compatibility-groups",
            get(catalogue_refs::list_compatibility_groups)
                .post(catalogue_refs::create_compatibility_group),
        )
        .route(
            "/api/compatibility-groups/:id",
            put(catalogue_refs::update_compatibility_group)
                .delete(catalogue_refs::delete_compatibility_group),
        )
        .route(
            "/api/disposable-packaging-types",
            get(catalogue_disposables::list_disposable_packaging_types)
                .post(catalogue_disposables::create_disposable_packaging_type),
        )
        .route(
            "/api/disposable-packaging-types/:id",
            put(catalogue_disposables::update_disposable_packaging_type)
                .delete(catalogue_disposables::delete_disposable_packaging_type),
        )
        // Matériaux, contenants et unités de mesure
        .route(
            "/api/packaging-materials",
            get(catalogue_units::list_packaging_materials)
                .post(catalogue_units::create_packaging_material),
        )
        .route(
            "/api/packaging-materials/:id",
            put(catalogue_units::update_packaging_material)
                .delete(catalogue_units::delete_packaging_material),
        )
        .route(
            "/api/container-types",
            get(catalogue_units::list_container_types).post(catalogue_units::create_container_type),
        )
        .route(
            "/api/container-types/:id",
            put(catalogue_units::update_container_type)
                .delete(catalogue_units::delete_container_type),
        )
        .route(
            "/api/units-of-measure",
            get(catalogue_units::list_units_of_measure)
                .post(catalogue_units::create_unit_of_measure),
        )
        .route(
            "/api/units-of-measure/:id",
            put(catalogue_units::update_unit_of_measure)
                .delete(catalogue_units::delete_unit_of_measure),
        )
        // Variantes & tarification
        .route(
            "/api/product-variants",
            get(catalogue_variants_and_prices::list_product_variants)
                .post(catalogue_variants_and_prices::create_product_variant),
        )
        .route(
            "/api/product-variants/:id",
            put(catalogue_variants_and_prices::update_product_variant)
                .delete(catalogue_variants_and_prices::delete_product_variant),
        )
        .route(
            "/api/supplier-prices",
            get(catalogue_variants_and_prices::list_supplier_prices)
                .post(catalogue_variants_and_prices::create_supplier_price),
        )
        .route(
            "/api/supplier-prices/:id",
            put(catalogue_variants_and_prices::update_supplier_price)
                .delete(catalogue_variants_and_prices::delete_supplier_price),
        )
        .route(
            "/api/customer-price-lists",
            get(catalogue_variants_and_prices::list_customer_price_lists)
                .post(catalogue_variants_and_prices::create_customer_price_list),
        )
        .route(
            "/api/customer-price-lists/:id",
            put(catalogue_variants_and_prices::update_customer_price_list)
                .delete(catalogue_variants_and_prices::delete_customer_price_list),
        )
        .route(
            "/api/customer-price-list-items",
            get(catalogue_price_items_and_history::list_customer_price_list_items)
                .post(catalogue_price_items_and_history::create_customer_price_list_item),
        )
        .route(
            "/api/customer-price-list-items/:id",
            put(catalogue_price_items_and_history::update_customer_price_list_item)
                .delete(catalogue_price_items_and_history::delete_customer_price_list_item),
        )
        .route(
            "/api/packaging-values",
            get(catalogue_price_items_and_history::list_packaging_values)
                .post(catalogue_price_items_and_history::create_packaging_value),
        )
        .route(
            "/api/packaging-values/:id",
            put(catalogue_price_items_and_history::update_packaging_value)
                .delete(catalogue_price_items_and_history::delete_packaging_value),
        )
        .route(
            "/api/price-history",
            get(catalogue_price_items_and_history::list_price_history),
        )
        // Administration OWNER & Catalogue V3
        .route(
            "/api/catalogue-products/:id/active",
            put(catalogue_v3::catalogue_set_product_active),
        )
        .route(
            "/api/catalogue-products/:id/reference-price",
            put(catalogue_v3::catalogue_set_reference_price)
                .get(catalogue_v3::catalogue_reference_price_history),
        )
        .route(
            "/api/catalogue-v3",
            get(catalogue_v3::product_catalogue_overview),
        )
        .route(
            "/api/catalogue-v3/brands",
            axum::routing::post(catalogue_v3::create_catalogue_brand),
        )
        .route(
            "/api/catalogue-v3/families",
            axum::routing::post(catalogue_v3::create_catalogue_family),
        )
        .route(
            "/api/catalogue-v3/units",
            axum::routing::post(catalogue_v3::create_catalogue_unit),
        )
        .route(
            "/api/catalogue-v3/products",
            get(catalogue_v3::list_catalogue_products_new)
                .post(catalogue_v3::create_catalogue_product_new),
        )
        .route(
            "/api/catalogue-v3/initialize",
            axum::routing::post(catalogue_v3::initialize_catalogue),
        )
        // Référentiels & unités V4 (BDBoisson)
        .route(
            "/api/breweries",
            get(catalogue_v4::list_breweries).post(catalogue_v4::create_brewery),
        )
        .route(
            "/api/breweries/:id",
            put(catalogue_v4::update_brewery).delete(catalogue_v4::delete_brewery),
        )
        .route(
            "/api/packaging-types",
            get(catalogue_v4::list_packaging_types).post(catalogue_v4::create_packaging_type),
        )
        .route(
            "/api/stock-locations",
            get(catalogue_v4::list_stock_locations).post(catalogue_v4::create_stock_location),
        )
        .route(
            "/api/sales-units",
            get(catalogue_v4::list_sales_units).post(catalogue_v4::create_sales_unit),
        )
        .route(
            "/api/sales-units/:id",
            put(catalogue_v4::update_sales_unit).delete(catalogue_v4::delete_sales_unit),
        )
        .route(
            "/api/products/:id/suppliers",
            get(catalogue_v4::list_product_suppliers).post(catalogue_v4::upsert_product_supplier),
        )
        .route(
            "/api/deposit-rules",
            get(catalogue_v4::list_deposit_rules).post(catalogue_v4::create_deposit_rule),
        )
}
